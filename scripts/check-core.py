"""Verify the bundled core against the published TextForge crate.

The snapshot in vendor/textforge is the published crate, file for file, with one
documented difference: Cargo.toml is the library-only manifest that
`library_manifest` derives from the published Cargo.toml.orig (no binaries,
examples, dev-dependencies or docs.rs metadata, and an empty workspace). No
engine file is edited.

    python3 scripts/check-core.py           # verify, offline
    python3 scripts/check-core.py --update  # copy the fetched crate, rewrite hashes

The published crate comes from Cargo's registry cache; run
`cargo fetch --manifest-path scripts/upstream/Cargo.toml` first. Use --update only
after a maintainer approved the new core version (AGENTS.md, section 17).
"""
from pathlib import Path
import hashlib
import json
import os
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / 'vendor/textforge'
PROVENANCE = ROOT / 'docs/core-provenance.json'
REVISION = ROOT / 'vendor/CORE_REVISION'
# Generated by Cargo for the registry, not part of the published sources we build.
SKIPPED = {'Cargo.lock'}
# Manifest sections that only build or document programs the addon never uses.
DROPPED_SECTIONS = {'[[bin]]', '[[example]]', '[dev-dependencies]', '[package.metadata.docs.rs]'}


def library_manifest(original: str) -> str:
    """Return Cargo.toml.orig without program sections and with an empty workspace."""
    lines = []
    section = None
    for line in original.splitlines(keepends=True):
        stripped = line.strip()
        if stripped.startswith('['):
            section = stripped
            if section == '[workspace]':
                lines.append(line)
                continue
        if section in DROPPED_SECTIONS or section == '[workspace]':
            continue
        lines.append(line)
    text = ''.join(lines).rstrip('\n') + '\n'
    return text.replace('\n\n\n[workspace]', '\n\n[workspace]')


def files(directory: Path) -> dict[str, str]:
    return {
        str(path.relative_to(directory)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted(directory.rglob('*'))
        if path.is_file() and 'target' not in path.parts and path.name not in SKIPPED
    }


manifest = json.loads(PROVENANCE.read_text())
version = manifest['version']
cargo = Path(os.environ.get('CARGO_HOME', Path.home() / '.cargo'))
candidates = sorted((cargo / 'registry/src').glob(f'*/textforge-{version}'))
if not candidates:
    raise SystemExit(
        f'textforge {version} is not in the Cargo registry cache; run '
        '`cargo fetch --manifest-path scripts/upstream/Cargo.toml`'
    )
upstream = candidates[0]
revision = json.loads((upstream / '.cargo_vcs_info.json').read_text())['git']['sha1']
assert revision == manifest['revision'], 'Published crate revision differs from the manifest'

if '--update' in sys.argv:
    if CORE.exists():
        shutil.rmtree(CORE)
    shutil.copytree(upstream, CORE, ignore=shutil.ignore_patterns(*SKIPPED, 'target'))
    (CORE / 'Cargo.toml').write_text(library_manifest((CORE / 'Cargo.toml.orig').read_text()))
    manifest['files'] = files(CORE)
    PROVENANCE.write_text(json.dumps(manifest, indent=2) + '\n')
    REVISION.write_text(revision + '\n')

actual = files(CORE)
published = files(upstream)
published.pop('Cargo.toml')
expected_manifest = library_manifest((upstream / 'Cargo.toml.orig').read_text())
assert (CORE / 'Cargo.toml').read_text() == expected_manifest, 'Cargo.toml is not the derived library manifest'
for relative, digest in published.items():
    assert actual.get(relative) == digest, f'Bundled file differs from the published crate: {relative}'
extra = set(actual) - set(published) - {'Cargo.toml'}
assert not extra, f'Files not in the published crate: {sorted(extra)}'
assert actual == manifest['files'], 'Bundled core content changed; review provenance'
assert REVISION.read_text().strip() == revision, 'vendor/CORE_REVISION differs from the crate'
print(f'Verified {len(actual)} bundled files against published textforge {version} ({revision[:7]})')
