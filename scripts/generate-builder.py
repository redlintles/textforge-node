"""Generate explicit builder methods, literal option unions and parity mapping.

Read the pinned core sources; run `python3 scripts/generate-builder.py` to update.
CI uses --check to detect stale methods, option lists and mappings.
No runtime method generation is used.
"""
from pathlib import Path
import re
import sys
import json
import hashlib

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / 'vendor/textforge'
api = (CORE / 'src/api/mod.rs').read_text()
registry = (CORE / 'src/globals/table.rs').read_text()
normalization = (CORE / 'src/tokens/transforms/unorm/mod.rs').read_text()
watchers = (CORE / 'src/api/portable/watchers.rs').read_text().split('const BUILTINS:')[1]
# Read accepted values from the engine's validation/registration declarations.
# These are type declarations only; all runtime validation remains in the core.
modes = re.findall(r'"(\w+)"\s*=>\s*Some\("\1"\)', normalization)
metrics = re.findall(r'"(\w+)"\s*,\s*crate::watchers::default_watchers::\w+', watchers)
if not modes or len(modes) != len(set(modes)) or not metrics or len(metrics) != len(set(metrics)):
    raise ValueError('Unexpected core literal-option declarations')
option_types = (
    '// Generated by scripts/generate-builder.py; do not edit by hand.\n'
    '/** Case-sensitive Unicode normalization modes accepted by the core. */\n'
    'export type NormalizationMode = ' + ' | '.join(repr(value) for value in modes) + ';\n\n'
    '/** Built-in watcher metric names; custom watcher names remain arbitrary strings. */\n'
    'export type BuiltinWatcherMetric =\n'
    + '\n'.join('  | ' + repr(value) for value in metrics) + ';\n'
)

syntax = {m[1]: re.findall(r'SyntaxToken::(String|Usize|Token)\b',m[2]) for m in re.finditer(r'(?s)\(\s*"(\w+)",\s*0x[0-9a-fA-F]+,.*?\[([^\]]*)\]\s*,?\s*\)',registry)}
def camel(value):
    head,*tail=value.split('_')
    return head+''.join(p.capitalize() for p in tail)
methods=[]
mapping=[]
trait=api.split('pub trait TextForgeConditionalMethods')[0]
for m in re.finditer(r'(?ms)^    fn (\w+)\(([^;]*?)\) -> Result<&mut Self, TextForgeError> \{\n(.*?)^    }',trait):
    name,signature,implementation=m.groups()
    token=re.search(r'Box::new\((\w+)::',implementation)[1]
    parameters=re.findall(r'(\w+): impl Into<ValType>',signature)
    kinds=syntax[token]
    if len(parameters)!=len(kinds): raise ValueError(name)
    typed=[];values=[]
    for param,kind in zip(parameters,kinds,strict=True):
        annotation,converter={'String':('TextArgument','textArg'),'Usize':('NumberArgument','numberArg'),'Token':('InstructionArgument','instructionArg')}[kind]
        if name == 'normalize_unicode' and param == 'mode': annotation = 'NormalizationMode | Variable'
        if name in {'val','var','mut_var'} and param=='var_value': annotation,converter='ValueArgument','valueArg'
        typed.append(f'{camel(param)}: {annotation}')
        values.append(f'{converter}({camel(param)})')
    args=', '.join([repr(token),*values])
    methods.append(f'  /** Mirrors Rust `TextForgeBuilderMethods::{name}` through `{token}`. */\n  {camel(name)}({", ".join(typed)}): Pipeline {{ return this.add({args}); }}\n')
    mapping.append({'rust':name,'javascript':camel(name),'mnemonic':token,'parameters':list(zip(parameters,kinds))})
if len(mapping)<70: raise ValueError('Unexpected builder shape')
output=ROOT/'ts/index.ts'
current=output.read_text();begin='  // BEGIN GENERATED BUILDER METHODS\n';end='  // END GENERATED BUILDER METHODS\n'
prefix,rest=current.split(begin);_,suffix=rest.split(end)
files={ROOT/'ts/options.ts':option_types, output:prefix+begin+''.join(methods)+end+suffix, ROOT/'docs/builder-parity.json':json.dumps({'coreVersion':'0.2.0','apiSha256':hashlib.sha256(api.encode()).hexdigest(),'registrySha256':hashlib.sha256(registry.encode()).hexdigest(),'methods':mapping},indent=2)+'\n'}
for path,content in files.items():
    if '--check' in sys.argv:
        if path.read_text()!=content: raise SystemExit(f'Stale generated file: {path}')
    else: path.write_text(content)
